"""Policy-driven synthetic data generator for end-of-turn detection.

Turns the frozen human policy (POLICY.md, data/gold_set.json) into a large
labeled training set. Pure code, seeded, reproducible; no LLM calls, so the
dataset can be regenerated byte-identically and audited line by line.

Design notes that matter:
- Every judgment-class rule from the calibration session is encoded here
  (H announced-continuation, J retraction, K self-retrieval vs narrated
  interruption). Settling hedges are deliberately NOT generated: the labeler
  put them at the boundary, so the model should learn them from nothing
  rather than from invented certainty.
- Truncation augmentation: complete utterances are also emitted cut mid-way
  and labeled wait, matching how ASR partials actually arrive.
- Every sample is emitted in a clean variant and an ASR-style variant
  (lowercased, terminal punctuation stripped) so the model cannot lean on
  punctuation as a crutch.
- Nothing here may collide with the frozen gold set; exact-text collisions
  are dropped at the end.
"""

